-- Classic TV Pakistan: isolated ARY catalogue for the full-site preview only.
-- Replace the email below with the exact Supabase Auth email used by the site admin,
-- then run this script in Supabase SQL Editor. This table is NOT used by the live site.
create table if not exists public."ExternalMediaTest" (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('ary')),
  title text not null,
  urdu_title text not null default '',
  series_url text not null,
  episode_number integer not null check (episode_number > 0),
  episode_title text not null default '',
  video_url text not null,
  thumbnail_url text not null default '',
  created_at timestamptz not null default now(),
  constraint external_media_test_provider_video_unique unique (provider, video_url)
);

alter table public."ExternalMediaTest" enable row level security;
grant select on public."ExternalMediaTest" to anon, authenticated;
grant insert, update, delete on public."ExternalMediaTest" to authenticated;

drop policy if exists "Public can read ARY test entries" on public."ExternalMediaTest";
create policy "Public can read ARY test entries"
on public."ExternalMediaTest" for select to anon, authenticated
using (true);

drop policy if exists "Only site admin can manage ARY test entries" on public."ExternalMediaTest";
create policy "Only site admin can manage ARY test entries"
on public."ExternalMediaTest" for all to authenticated
using ((auth.jwt() ->> 'email') = 'REPLACE_WITH_ADMIN_EMAIL')
with check ((auth.jwt() ->> 'email') = 'REPLACE_WITH_ADMIN_EMAIL');
