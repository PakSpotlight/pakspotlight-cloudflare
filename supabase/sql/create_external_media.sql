-- Classic TV Pakistan: separate catalogue for official third-party media links.
-- Run this in Supabase SQL Editor before using Admin Studio > ARY Digital.
create table if not exists public."ExternalMedia" (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('ary')),
  title text not null,
  urdu_title text not null default '',
  series_url text not null,
  episode_number integer not null check (episode_number > 0),
  episode_title text not null default '',
  video_url text not null,
  thumbnail_url text not null default '',
  created_at timestamptz not null default now(),
  constraint external_media_provider_video_unique unique (provider, video_url)
);
alter table public."ExternalMedia" enable row level security;
drop policy if exists "Authenticated admins manage external media" on public."ExternalMedia";
create policy "Authenticated admins manage external media"
on public."ExternalMedia" for all to authenticated
using (true) with check (true);
